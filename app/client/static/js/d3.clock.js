 // Set radius of clocks pins
    var hourRadius = 150;
    var minuteRadius = 170;
    var secondRadius = 190;
    var start_x = 570;
    var start_y = 240;

var describeArc, polarToCartesian, setCaptions;
polarToCartesian = function(centerX, centerY, radius, angleInDegrees) {
    var angleInRadians;
    angleInRadians = (angleInDegrees - 90) * Math.PI / 180.0;
    return {
        x: centerX + radius * Math.cos(angleInRadians),
        y: centerY + radius * Math.sin(angleInRadians)
    };
};

describeArc = function(x, y, radius, startAngle, endAngle) {
    var arcSweep, end, start;
    start = polarToCartesian(x, y, radius, endAngle);
    end = polarToCartesian(x, y, radius, startAngle);
    arcSweep = endAngle - startAngle <= 180 ? '0' : '1';
    return ['M', start.x, start.y, 'A', radius, radius, 0, arcSweep, 0, end.x, end.y].join(' ');
};

setCaptions = function() {
  var dot, hour, hourArc, minArc, secondArc, minute, now, pos;
  now = new Date();

    hour = now.getHours() % 12;
    minute = now.getMinutes();
    second = now.getSeconds();

    hourArc = (hour * 60 + minute) / (12 * 60) * 360;
    minArc = minute / 60 * 360;
    secArc = 360 * (second/60);
    //[DEBUG] Log the Seconds and wrt angles deg
    //console.log(second / 60*60, (360 * (second/59)));


    $('.clockArc.hour').attr('d', describeArc(start_x, start_y, hourRadius, 0, hourArc));
    $('.clockArc.minute').attr('d', describeArc(start_x, start_y, minuteRadius, 0, minArc));
    $('.clockArc.second').attr('d', describeArc(start_x, start_y, secondRadius, 0, secArc));

    $('.clockDot.hour').attr('d', describeArc(start_x, start_y, hourRadius, hourArc - 3, hourArc));
    $('.clockDot.minute').attr('d', describeArc(start_x, start_y, minuteRadius, minArc - 1, minArc));
    $('.clockDot.second').attr('d', describeArc(start_x, start_y, secondRadius, secArc - -1, secArc));

    dot = $(".clockDot.hour");
    pos = polarToCartesian(start_x, start_y, hourRadius, hourArc);
    dot.attr("cx", pos.x);
    dot.attr("cy", pos.y);

    dot = $(".clockDot.minute");
    pos = polarToCartesian(start_x, start_y, minuteRadius, minArc);
    dot.attr("cx", pos.x);
    dot.attr("cy", pos.y);

    dot = $(".clockDot.second");
    pos = polarToCartesian(start_x, start_y, secondRadius, secArc);
    dot.attr("cx", pos.x);
    dot.attr("cy", pos.y);

    // Now setting the main clock time and second value/text
    $('#timeSeconds').text('' + moment().tz('Asia/Tokyo').format('ss'));
    $('#time').text(moment().format('H:mm'));

    // Set the Year, date, month on the left of the clock
    $('#timezone').text('Timezone - ' + moment.tz.guess());
    $('#day').text(moment().format('dddd'));
    $('#year-and-date').text(moment().format('YYYY MMMM D'));

    // Setting other times for other timezones
    $('#istTime').text('IST: ' + moment().tz('Asia/Kolkata').format('H:mm | dddd | D/M'));
    $('#gmtTime').text('GMT: ' + moment().tz('Europe/London').format('H:mm | dddd | D/M'));
    $('#edtTime').text('EDT: ' + moment().tz('America/New_York').format('H:mm | dddd | D/M'));
    $('#jstTime').text('JST: ' + moment().tz('Asia/Tokyo').format('H:mm | dddd | D/M'));

    //[DEBUG]: degree value
    $('#msg').text(secArc);

    return 0;
};

// Since, we are not updating the date, year month hence keeping out side of setCaptions method
// set the author
$('#author').text(author);

setCaptions();

setInterval(function() {
  return setCaptions();
}, 1000);

